def _normalize(raw: str) -> str:
    key = raw.lower().strip()

    if key in _APP_ALIASES:
        return _APP_ALIASES[key].get(_SYSTEM, raw)

    for alias_key, os_map in _APP_ALIASES.items():
        if alias_key in key or key in alias_key:
            return os_map.get(_SYSTEM, raw)

    return raw  

# ── Is it already open? ───────────────────────────────────────────────────────
# Launching a second copy of something that is already running is the wrong
# answer to "open Chrome": the new process hands its request to the one that is
# up and exits, and the window the user actually wanted stays behind the
# terminal they spoke into. So look for a window first and only launch when
# there is none — which is also what the taskbar does when you click an icon.
#
# The process name is not always the thing you type to start it, hence the
# overrides: `wt` starts Terminal but the process is WindowTerminal, and Teams
# has shipped as both Teams.exe and ms-teams.exe.
_PROC_OVERRIDES: dict[str, set[str]] = {
    "wt":       {"windowsterminal"},
    "msteams":  {"teams", "ms-teams"},
    "ms-teams": {"teams", "ms-teams"},
    "settings": set(),            # ms-settings: has no process of that name
}

# Windows that belong to a running app but are not the app's window. Program
# Manager is the desktop itself, owned by explorer, so without this "open File
# Explorer" would raise the wallpaper and never open a folder.
_NOT_A_WINDOW = {"", "program manager", "windows shell experience"}


def _process_names(app_name: str) -> set[str]:
    base = app_name.replace("\\", "/").split("/")[-1].lower()
    base = base.split(":", 1)[0].strip()
    for suffix in (".exe", ".msi", ".bat", ".lnk"):
        if base.endswith(suffix):
            base = base[: -len(suffix)]
    names = {base, base.replace(" ", ""), base.replace(" ", "-")}
    names |= _PROC_OVERRIDES.get(base, set())
    return {n for n in names if n}


def _running_pids(app_name: str) -> set[int]:
    """Pids of processes whose executable is this app; empty when unsure."""
    if not _PSUTIL:
        return set()
    names = _process_names(app_name)
    if not names:
        return set()
    pids: set[int] = set()
    try:
        for proc in psutil.process_iter(["pid", "name"]):
            try:
                name = (proc.info["name"] or "").lower()
                if name.endswith(".exe"):
                    name = name[:-4]
                if name in names:
                    pids.add(int(proc.info["pid"]))
            except Exception:
                continue
    except Exception as e:
        print(f"[open_app] process scan failed: {e}")
    return pids


def _focus_windows(pids: set[int], app_name: str) -> str:
    """Raise the app's window and return its title, '' when there is none.

    The pid is what decides, because a title match alone finds the wrong window
    often enough to matter — a browser tab titled "WhatsApp Web" is not the
    desktop app. With no psutil there is nothing better than the title, so that
    fallback is kept for that case alone.
    """
    try:
        import pygetwindow as gw
        import win32con
        import win32gui
        import win32process
    except Exception as e:
        print(f"[open_app] window focus unavailable: {e}")
        return ""

    hint = app_name.lower().split(".")[0].strip()
    for win in gw.getAllWindows():
        try:
            hwnd = win._hWnd
            title = (win32gui.GetWindowText(hwnd) or "").strip()
            if title.lower() in _NOT_A_WINDOW:
                continue
            if getattr(win, "width", 0) < 100 or getattr(win, "height", 0) < 100:
                continue
            _, pid = win32process.GetWindowThreadProcessId(hwnd)
            pid = int(pid)
        except Exception:
            continue

        if pids:
            if pid not in pids:
                continue
        elif not (hint and hint in title.lower()):
            continue

        try:
            if win32gui.IsIconic(hwnd):
                win32gui.ShowWindow(hwnd, win32con.SW_RESTORE)
            elif not win32gui.IsWindowVisible(hwnd):
                win32gui.ShowWindow(hwnd, win32con.SW_SHOW)
            win32gui.SetForegroundWindow(hwnd)
        except Exception as e:
            # Windows refuses foreground to a process that is not itself in
            # front, and the answer still was "here is the window that is
            # already open" — not "launch a copy the user did not ask for".
            print(f"[open_app] could not raise '{title}': {e}")
        return title
    return ""


def _focus_running(app_name: str) -> str:
    return _focus_windows(_running_pids(app_name), app_name)


def _launch_windows(app_name: str) -> bool:

    if shutil.which(app_name) or shutil.which(app_name.split(".")[0]):
        try:
            subprocess.Popen(
                app_name,
                shell=True,
                stdout=subprocess.DEVNULL,
                stderr=subprocess.DEVNULL,
            )
            time.sleep(1.5)
            return True
        except Exception as e:
            print(f"[open_app] subprocess failed: {e}")

    if ":" in app_name:
        try:
            subprocess.Popen(f"start {app_name}", shell=True)
            time.sleep(1.0)
            return True
        except Exception:
            pass

    try:
        import pyautogui
        pyautogui.PAUSE = 0.1
        pyautogui.press("win")
        time.sleep(0.7)
        pyautogui.write(app_name, interval=0.05)
        time.sleep(0.9)
        pyautogui.press("enter")
        time.sleep(2.5)
        return True
    except Exception as e:
        print(f"[open_app] Start Menu search failed: {e}")

    return False


def _launch_macos(app_name: str) -> bool:

    try:
        result = subprocess.run(
            ["open", "-a", app_name],
            capture_output=True, timeout=8
        )
        if result.returncode == 0:
            time.sleep(1.0)
            return True
    except Exception:
        pass

    try:
        result = subprocess.run(
            ["open", "-a", f"{app_name}.app"],
            capture_output=True, timeout=8
        )
        if result.returncode == 0:
            time.sleep(1.0)
            return True
    except Exception:
        pass

    binary = shutil.which(app_name) or shutil.which(app_name.lower())
    if binary:
        try:
            subprocess.Popen(
                [binary],
                stdout=subprocess.DEVNULL,
                stderr=subprocess.DEVNULL
            )
            time.sleep(1.0)
            return True
        except Exception:
            pass

    try:
        import pyautogui
        pyautogui.hotkey("command", "space")
        time.sleep(0.6)
        pyautogui.write(app_name, interval=0.05)
        time.sleep(0.8)
        pyautogui.press("enter")
        time.sleep(1.5)
        return True
    except Exception as e:
        print(f"[open_app] Spotlight failed: {e}")

    return False


_LINUX_TERMINAL_FALLBACKS = [
    "x-terminal-emulator", "gnome-terminal", "konsole", "xfce4-terminal",
    "xterm", "lxterminal", "mate-terminal", "tilix", "alacritty", "kitty",
]

def _launch_linux(app_name: str) -> bool:

    # terminal emulators: try common ones in order
    if app_name in ("x-terminal-emulator", "gnome-terminal", "terminal"):
        for term in _LINUX_TERMINAL_FALLBACKS:
            if shutil.which(term):
                try:
                    subprocess.Popen([term], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
                    time.sleep(1.0)
                    return True
                except Exception:
                    continue

    binary = (
        shutil.which(app_name) or
        shutil.which(app_name.lower()) or
        shutil.which(app_name.lower().replace(" ", "-")) or
        shutil.which(app_name.lower().replace(" ", "_"))
    )
    if binary:
        try:
            subprocess.Popen(
                [binary],
                stdout=subprocess.DEVNULL,
                stderr=subprocess.DEVNULL
            )
            time.sleep(1.0)
            return True
        except Exception:
            pass

    try:
        subprocess.run(
            ["xdg-open", app_name],
            capture_output=True, timeout=5
        )
        return True
    except Exception:
        pass

    for desktop_name in [
        app_name.lower(),
        app_name.lower().replace(" ", "-"),
        app_name.lower().replace(" ", ""),
    ]:
        try:
            result = subprocess.run(
                ["gtk-launch", desktop_name],
                capture_output=True, timeout=5
            )
            if result.returncode == 0:
                return True
        except Exception:
            pass

    return False


_OS_LAUNCHERS = {
    "Windows": _launch_windows,
    "Darwin":  _launch_macos,
    "Linux":   _launch_linux,
}

def open_app(
    parameters=None,
    response=None,
    player=None,
    session_memory=None,
) -> str:
    app_name = (parameters or {}).get("app_name", "").strip()

    if not app_name:
        return "No application name provided."

    launcher = _OS_LAUNCHERS.get(_SYSTEM)
    if launcher is None:
        return f"Unsupported operating system: {_SYSTEM}"

    normalized = _normalize(app_name)
    print(f"[open_app] Launching: '{app_name}' → '{normalized}' ({_SYSTEM})")

    if player:
        player.write_log(f"[open_app] {app_name}")

    # Already running? Bring the existing window forward instead of starting a
    # second process. macOS `open -a` activates a running app by itself, and
    # Linux has no equivalent that works without a desktop session, so both
    # are left to launch as before.
    if _SYSTEM == "Windows":
        for candidate in (normalized, app_name):
            title = _focus_running(candidate)
            if title:
                print(f"[open_app] already open, focused: '{title}'")
                return (f"{app_name} was already open — I brought its window "
                        f"to the front instead of starting a second copy.")

    try:
        if launcher(normalized):
            return f"Opened {app_name}."
        if normalized.lower() != app_name.lower():
            if launcher(app_name):
                return f"Opened {app_name}."
        return (
            f"Could not confirm that {app_name} launched. "
            f"It may still be loading, or it might not be installed."
        )
    except Exception as e:
        print(f"[open_app] Error: {e}")
        return f"Failed to open {app_name}: {e}"


